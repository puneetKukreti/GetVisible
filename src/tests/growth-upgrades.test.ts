  describe('Upgrade 2: CSV Import with Auto-Generate Demos', () => {
    it('auto-generates and approves website demos when autoGenerateDemos is true', async () => {
      const csvData = `business_name,profession,city,phone,address
"Dr. Kapoor Dental Spa","Dentist","Gurgaon","9811122233","Sector 54, Golf Course Road, Gurgaon"`;

      const req = new NextRequest('http://localhost:3000/api/discovery/csv-import', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-organization-id': DEMO_ORGANIZATION_ID,
          cookie: await ownerSessionCookie(),
        },
        body: JSON.stringify({
          csvContent: csvData,
          autoGenerateDemos: true,
        }),
      });

      const res = await csvImportPOST(req);
      expect(res.status).toBe(200);

      const json = await res.json();
      expect(json.success).toBe(true);
      expect(json.imported).toBeGreaterThanOrEqual(1);
      expect(json.demosGenerated).toBeGreaterThanOrEqual(1);

      // Verify the lead and demo were created
      const importedLeadId = json.results?.[0]?.leadId;
      expect(importedLeadId).toBeDefined();

      const demos = await WebsiteDemoRepository.listDemos(DEMO_ORGANIZATION_ID, importedLeadId);
      expect(demos.length).toBeGreaterThanOrEqual(1);
      expect(demos[0].approvalStatus).toBe('APPROVED');
    });
  });

