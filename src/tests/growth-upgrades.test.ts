import { describe, it, expect, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';
import { generateDeterministicOutreach } from '@/lib/sales/outreach';
import { POST as batchGeneratePOST } from '@/app/api/demos/batch-generate/route';
import { POST as sendWhatsappPOST } from '@/app/api/outreach/send-whatsapp/route';
import { POST as csvImportPOST } from '@/app/api/discovery/csv-import/route';
import { LeadRepository, WebsiteDemoRepository } from '@/lib/db/repository';
import { DEMO_ORGANIZATION_ID } from '@/lib/db/demo-data';

describe('Growth & Workflow Upgrades', () => {
  beforeEach(async () => {
    // Reset/ensure data clean state
  });

  describe('Upgrade 1: Zero-Link WhatsApp Strategy', () => {
    it('generates a Touch 1 zero-link message with NO URLs and references screenshot and PREVIEW hook', () => {
      const outreach = generateDeterministicOutreach({
        businessName: 'Sharma & Singhal CA',
        profession: 'Chartered Accountant',
        city: 'Gurgaon',
        demoUrl: 'https://getvisible.in/demo/sharma-ca',
        screenshotUrl: 'https://getvisible.in/api/demos/123/screenshot.png',
        websiteStatus: 'NO_WEBSITE',
        publicPhone: '9876543210',
      });

      expect(outreach.whatsappMessage).toBeDefined();
      const touch1 = outreach.whatsappMessage!;

      // ZERO-LINK check: must not contain http, https, or domain links
      expect(touch1).not.toContain('http://');
      expect(touch1).not.toContain('https://');
      expect(touch1).not.toContain('.com');
      expect(touch1).not.toContain('.in');

      // Trust building elements
      expect(touch1).toContain('Sharma & Singhal CA');
      expect(touch1).toContain('screenshot attached above 👆');
      expect(touch1).toContain('cautious with unknown links');
      expect(touch1).toContain('PREVIEW');
    });

    it('generates a Touch 2 follow-up reply that includes the demo live link', () => {
      const outreach = generateDeterministicOutreach({
        businessName: 'Mehta Clinic',
        profession: 'Dentist',
        city: 'Noida',
        demoUrl: 'https://getvisible.in/demo/mehta-clinic-token',
        screenshotUrl: 'https://getvisible.in/api/demos/456/screenshot.png',
        websiteStatus: 'NO_WEBSITE',
        publicPhone: '9876543210',
      });

      expect(outreach.whatsappFollowUpWithLink).toBeDefined();
      const touch2 = outreach.whatsappFollowUpWithLink!;

      expect(touch2).toContain('Thanks for replying!');
      expect(touch2).toContain('https://getvisible.in/demo/mehta-clinic-token');
      expect(touch2).toContain('Mehta Clinic');
      expect(touch2).toContain('48 hours');
    });
  });

  describe('Upgrade 2: CSV Import with Auto-Generate Demos', () => {
    it('auto-generates and approves website demos when autoGenerateDemos is true', async () => {
      const csvData = `business_name,profession,city,phone,address
"Dr. Kapoor Dental Spa","Dentist","Gurgaon","9811122233","Sector 54, Golf Course Road, Gurgaon"`;

      const req = new NextRequest('http://localhost:3000/api/discovery/csv-import', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-organization-id': DEMO_ORGANIZATION_ID,
        },
        body: JSON.stringify({
          csvContent: csvData,
          autoGenerateDemos: true,
        }),
      });

      const res = await csvImportPOST(req);
      expect(res.status).toBe(200);

      const json = await res.json();
      expect(json.success).toBe(true);
      expect(json.imported).toBeGreaterThanOrEqual(1);
      expect(json.demosGenerated).toBeGreaterThanOrEqual(1);

      // Verify the lead and demo were created
      const importedLeadId = json.results?.[0]?.leadId;
      expect(importedLeadId).toBeDefined();

      const demos = await WebsiteDemoRepository.listDemos(DEMO_ORGANIZATION_ID, importedLeadId);
      expect(demos.length).toBeGreaterThanOrEqual(1);
      expect(demos[0].approvalStatus).toBe('APPROVED');
    });
  });

  describe('Upgrade 3: Batch Demo Generation Endpoint', () => {
    it('generates and approves demos for leads with NO_WEBSITE', async () => {
      // Create a test lead without demo
      const testLead = await LeadRepository.createLead(
        {
          businessName: 'Rawat & Sons Tax Consultants',
          profession: 'Chartered Accountant',
          city: 'Faridabad',
          address: 'Sector 15, Faridabad',
          websiteStatus: 'NO_WEBSITE',
          publicPhone: '+91 99887 76655',
        },
        DEMO_ORGANIZATION_ID,
        'Test Suite'
      );

      const req = new NextRequest('http://localhost:3000/api/demos/batch-generate', {
        method: 'POST',
        headers: {
          'x-organization-id': DEMO_ORGANIZATION_ID,
        },
      });

      const res = await batchGeneratePOST(req);
      expect(res.status).toBe(200);

      const json = await res.json();
      expect(json.success).toBe(true);
      expect(json.totalReady).toBeGreaterThan(0);

      const demos = await WebsiteDemoRepository.listDemos(DEMO_ORGANIZATION_ID, testLead.id);
      expect(demos.length).toBeGreaterThanOrEqual(1);
      expect(demos[0].approvalStatus).toBe('APPROVED');
    });
  });

  describe('Upgrade 4: 1-Click WhatsApp Send / Blitz Endpoint', () => {
    it('marks lead as CONTACTED and returns WEB_ASSISTED mode when webhook is not configured', async () => {
      const testLead = await LeadRepository.createLead(
        {
          businessName: 'Blitz Test Architecture',
          profession: 'Architect',
          city: 'Gurgaon',
          address: 'Cyber City, Gurgaon',
          websiteStatus: 'NO_WEBSITE',
          publicPhone: '+91 98765 43210',
        },
        DEMO_ORGANIZATION_ID,
        'Test Suite'
      );

      const req = new NextRequest('http://localhost:3000/api/outreach/send-whatsapp', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-organization-id': DEMO_ORGANIZATION_ID,
        },
        body: JSON.stringify({
          leadId: testLead.id,
          phone: '919876543210',
          message: 'Zero-link message pitch test',
          notes: 'Test dispatch',
        }),
      });

      const res = await sendWhatsappPOST(req);
      expect(res.status).toBe(200);

      const json = await res.json();
      expect(json.success).toBe(true);
      expect(json.mode).toBe('WEB_ASSISTED');

      // Verify lead transitioned to CONTACTED
      const updatedLead = await LeadRepository.getLeadById(testLead.id, DEMO_ORGANIZATION_ID);
      expect(updatedLead?.leadStatus).toBe('CONTACTED');
    });
  });
});
